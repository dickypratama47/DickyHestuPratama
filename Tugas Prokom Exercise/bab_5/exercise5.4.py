# Versi 1: Mengeksekusi blok if (kondisi hijau terpenuhi)
print("--- Versi 1 ---")
warna_alien = 'hijau'

if warna_alien == 'hijau':
    print("Selamat! Anda mendapat 5 poin karena menembak alien hijau.")
else:
    print("Selamat! Anda mendapat 10 poin.")

# Versi 2: Mengeksekusi blok else (kondisi hijau tidak terpenuhi)
print("\n--- Versi 2 ---")
warna_alien = 'kuning'

if warna_alien == 'hijau':
    print("Selamat! Anda mendapat 5 poin karena menembak alien hijau.")
else:
    print("Selamat! Anda mendapat 10 poin.")